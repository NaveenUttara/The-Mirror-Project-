export type TranslationKey = keyof typeof translations.en;

export function getStoredLanguage(): Language {
    if (typeof window === 'undefined') return 'en';
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === 'kn' ? 'kn' : 'en';
}

export function t(language: Language) {
    return translations[language];
}

export function formatMessage(template: string, values: Record<string, string | number>) {
    return Object.entries(values).reduce(
        (message, [key, value]) => message.replaceAll(`{${key}}`, String(value)),
        template,
    );
}

export function translateStatus(language: Language, status: string) {
    const labels = translations[language].status;
    return labels[status] || status.replaceAll('_', ' ');
}

export function translateSeverity(language: Language, severity: string) {
    const labels = translations[language].severity;
    return labels[severity.toLowerCase()] || severity;
}
